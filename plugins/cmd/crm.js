// Plugin: crm
// Copy and Re-send Message (CRM) for Alya V12
// Commands: crm
// Author: Ryuhan (adapted for Alya V12 ctx system)
const { generateWAMessageFromContent, proto } = require('@whiskeysockets/baileys')

const path = require('path')
const { getContentType } = require('@whiskeysockets/baileys')

module.exports = {
  command: ['crm'],
  tags: ['owner'],
  run: async (alya, m, ctx) => {
    const {
      command, args, text, q, prefix, body, budy,
      sender, from, pushname, botNumber,
      isCmd, isGroup, isMedia, isImage, isVideo, isAudio, isSticker,
      isQuotedImage, isQuotedVideo, isQuotedSticker, isQuotedAudio,
      isQuotedDocument, isQuotedViewOnce, isQuotedLocation, isQuotedContact,
      groupMetadata, groupName, groupMembers, groupAdmins, groupOwner,
      isBotAdmins, isGroupAdmins, isAdmins, isAdminOrOwner,
      Ryuu, isPrem, isAly, isAlya, isSewa, jangan,
      quoted, mime, qmsg, content, type, chatUpdate, store,
      reply, replyalya, replytolak, replyprem,
      senderNumber, chath, pes, messagesC, bady,
      waifuList, husbuList, pler, setting, user
    } = ctx

    // Only owner/superadmin
    if (!Ryuu) return replytolak('⚠️ Fitur ini hanya untuk Owner.')

    // Parse flags dari args
    // Usage: .crm --raw | .crm --run
    const rawArgs = (text || '').trim()
    const isRaw = /--raw\b/.test(rawArgs)
    const isRun = /--run\b/.test(rawArgs)

    // ============================================================
    // .crm --run
    // Reply pesan dokumen .js lalu jalankan isinya sebagai kode
    // ============================================================
    if (isRun) {
      if (!m.quoted) return reply('❌ Reply pesan file *.js* yang ingin dijalankan dengan *.crm --run*')

      // Harus quoted dokumen
      const qMsg = m.quoted
      const qMime = qMsg?.mimetype || ''
      const qType = getContentType(qMsg?.message || {})

      const isDoc = isQuotedDocument || qType === 'documentMessage' || /javascript|text/.test(qMime)
      if (!isDoc) return reply('❌ Pesan yang di-reply harus berupa file dokumen *.js*')

      let buffer
      try {
        buffer = await qMsg.download()
      } catch (e) {
        return reply(`❌ Gagal mendownload file: ${e.message}`)
      }

      if (!buffer || !buffer.length) return reply('❌ File kosong atau gagal diunduh.')

      const code = buffer.toString('utf8')

      try {
        // Inject alya & m ke dalam scope eval agar kode bisa pakai keduanya
        const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor
        // Wrap dengan ctx-like environment
        const fn = new AsyncFunction('alya', 'm', 'ctx', 'reply', 'replyalya', code)
        await fn(alya, m, ctx, reply, replyalya)
        await reply('✅ *Script berhasil dijalankan.*')
      } catch (e) {
        return reply(`❌ *Run Error:*\n\`\`\`${e.message}\`\`\``)
      }
      return
    }

    // ============================================================
    // .crm --raw
    // Reply pesan apapun → kirim JSON proto-nya sebagai file .js
    // siap di-eval / dianalisis
    // ============================================================
    if (isRaw) {
      if (!m.quoted) return reply('❌ Reply pesan yang ingin di-inspect dengan *.crm --raw*')

      const qMsg = m.quoted
      const targetMessage = qMsg?.message || {}
      const msgType = getContentType(targetMessage) || 'unknownMessage'

      // Build eval-ready script (mirip format CRM asli dari Rimuru MD)
      const jsonContent = JSON.stringify(targetMessage, null, 2)
      const script = `/**
 * Generated by .crm --raw (Alya V12)
 * Original Type : ${msgType}
 * From          : ${qMsg?.sender || 'unknown'}
 * Chat          : ${m.chat}
 */

// Kirim ulang pesan ini dengan relayMessage (paling akurat)
// Cara pakai: simpan file ini, lalu .crm --run

const { proto, generateWAMessageFromContent, generateForwardMessageContent } = require('@whiskeysockets/baileys')

const rawMessage = ${jsonContent}

// Contoh: relay ulang sebagai forward
const fakeProto = proto.WebMessageInfo.fromObject({
  key: { remoteJid: m.chat, fromMe: false, id: 'crm_raw_' + Date.now() },
  message: rawMessage,
  messageTimestamp: Math.floor(Date.now() / 1000),
})

const forwardContent = await generateForwardMessageContent(fakeProto, false)
const forwardMsg = await alya.generateWAMessage(m.chat, { forward: fakeProto }, { userJid: alya.user.id })
await alya.relayMessage(m.chat, forwardMsg.message, { messageId: forwardMsg.key.id })
`

      const filename = `crm_${msgType}_${Date.now()}.js`

      try {
        await alya.sendMessage(m.chat, {
          document: Buffer.from(script, 'utf8'),
          mimetype: 'text/javascript',
          fileName: filename,
          caption: `📦 *CRM --raw*\n\n` +
            `• *Type  :* \`${msgType}\`\n` +
            `• *From  :* ${qMsg?.sender?.split('@')[0] || 'unknown'}\n` +
            `• *File  :* \`${filename}\`\n\n` +
            `_Reply file ini dengan \`.crm --run\` untuk menjalankannya._`
        }, { quoted: m })
      } catch (e) {
        return reply(`❌ Gagal mengirim file: ${e.message}`)
      }
      return
    }

    // ============================================================
    // .crm (default — tanpa flag)
    // Reply pesan → forward ulang 100% mirip (copy relay)
    // ============================================================
    if (!m.quoted) {
      return reply(
        `*📋 CRM — Copy & Re-send Message*\n\n` +
        `Gunakan dengan me-reply pesan yang ingin diproses:\n\n` +
        `• \`${prefix}crm\` → Forward ulang pesan secara identik\n` +
        `• \`${prefix}crm --raw\` → Ambil raw proto pesan sebagai file .js\n` +
        `• \`${prefix}crm --run\` → Jalankan file .js yang di-reply sebagai kode\n\n` +
        `_Semua mode hanya untuk Owner._`
      )
    }

    // Default: forward/relay ulang pesan yang di-reply
    try {
      const fakeObj = m.quoted?.fakeObj
      if (!fakeObj) return reply('❌ Gagal mendapatkan objek pesan quoted.')
      await alya.sendMessage(m.chat, { forward: fakeObj }, { quoted: m })
    } catch (e) {
      return reply(`❌ Gagal menduplikasi pesan: ${e.message}`)
    }
  }
}
