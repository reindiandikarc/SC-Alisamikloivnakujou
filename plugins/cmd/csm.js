// Plugin: csm (Copy Send Message)
// Ported from Alya V12 → V13
// Commands: csm
// Sub-flags: --raw, --raw --js, --run [id], --run (reply .js), --list, --del [id]

module.exports = {
  command: ['csm'],
  tags: ['owner'],
  run: async (alya, m, ctx) => {
    const {
      args, prefix,
      Ryuu,
      reply, replyalya, replytolak,
      fs
    } = ctx

    if (!Ryuu) return replytolak(mess.only.owner)

    const { proto, getContentType } = require('@whiskeysockets/baileys')
    const { downloadMediaMessage } = require('@whiskeysockets/baileys')
    const path = require('path')

    // ── Init database CSM ──
    const csmDbPath = './database/csm.json'
    if (!fs.existsSync(csmDbPath)) {
      fs.writeFileSync(csmDbPath, JSON.stringify({ messages: {}, nextId: 1 }, null, 2))
    }
    let csmDb = JSON.parse(fs.readFileSync(csmDbPath))
    const saveCsmDb = () => fs.writeFileSync(csmDbPath, JSON.stringify(csmDb, null, 2))

    // ── Parse flags ──
    const hasRaw  = args.includes('--raw')
    const hasRun  = args.includes('--run')
    const hasList = args.includes('--list')
    const hasDel  = args.includes('--del')
    const hasJs   = args.includes('--js')
    const cleanArgs = args.filter(a => !a.startsWith('--'))
    const argId   = cleanArgs[0]

    // ── HELP ──
    if (!hasRaw && !hasRun && !hasList && !hasDel) {
      return replyalya(
        `╭─「 *CSM - Copy Send Message* 」\n` +
        `│\n` +
        `├ *${prefix}csm --raw*\n` +
        `│  Reply pesan → simpan ke database\n` +
        `│  (foto, video, audio, button, doc, dll)\n` +
        `│\n` +
        `├ *${prefix}csm --raw --js*\n` +
        `│  Reply pesan → simpan + ekspor file .js\n` +
        `│\n` +
        `├ *${prefix}csm --run [id]*\n` +
        `│  Replay pesan dari database by ID\n` +
        `│\n` +
        `├ *${prefix}csm --run*\n` +
        `│  Reply file .js → eksekusi kode\n` +
        `│\n` +
        `├ *${prefix}csm --list*\n` +
        `│  Lihat semua pesan tersimpan\n` +
        `│\n` +
        `└ *${prefix}csm --del [id]*\n` +
        `   Hapus pesan dari database`
      )
    }

    // ══════════════════════════════════════════════
    // --raw : Capture quoted message → simpan ke DB
    // ══════════════════════════════════════════════
    if (hasRaw) {
      if (!m.quoted) return replyalya('❌ Reply dulu pesan yang ingin di-capture ya~')

      const quotedFake = m.quoted.fakeObj
      if (!quotedFake || !quotedFake.message) return replyalya('❌ Pesan reply tidak valid.')

      const msgType = getContentType(quotedFake.message)
      if (!msgType) return replyalya('❌ Tipe pesan tidak dikenali.')

      // Simpan ke database
      const newId = csmDb.nextId++
      csmDb.messages[newId] = {
        id: newId,
        type: msgType,
        sender: m.quoted.sender || m.sender,
        senderName: m.quoted.name || m.pushName || 'Unknown',
        chat: m.quoted.chat || m.chat,
        timestamp: Date.now(),
        message: quotedFake.message
      }
      saveCsmDb()

      await replyalya(
        `✅ *CSM berhasil disimpan!*\n\n` +
        `🆔 ID    : *${newId}*\n` +
        `📦 Tipe  : *${msgType.replace(/Message$/i, '')}*\n` +
        `👤 Dari  : ${csmDb.messages[newId].senderName}\n` +
        `📊 Total DB : ${Object.keys(csmDb.messages).length} pesan\n\n` +
        `Replay → *${prefix}csm --run ${newId}*`
      )

      // Export file .js jika ada flag --js
      if (hasJs) {
        const jsScript =
          `/**\n` +
          ` * Generated by CSM --raw\n` +
          ` * ID        : ${newId}\n` +
          ` * Type      : ${msgType}\n` +
          ` * Timestamp : ${new Date().toISOString()}\n` +
          ` * Bot       : SC Alya V13\n` +
          ` */\n\n` +
          `const { proto } = require('@whiskeysockets/baileys')\n` +
          `const crypto = require('crypto')\n\n` +
          `const rawMessage = ${JSON.stringify(quotedFake.message, null, 2)}\n\n` +
          `const fakeObj = proto.WebMessageInfo.fromObject({\n` +
          `  key: {\n` +
          `    remoteJid: m.chat,\n` +
          `    fromMe: false,\n` +
          `    id: crypto.randomBytes(8).toString('hex').toUpperCase()\n` +
          `  },\n` +
          `  message: rawMessage\n` +
          `})\n\n` +
          `await alya.copyNForward(m.chat, fakeObj, true)\n`

        await alya.sendMessage(m.chat, {
          document: Buffer.from(jsScript),
          mimetype: 'text/javascript',
          fileName: `csm_${newId}_${msgType.replace(/Message$/i, '')}.js`,
          caption: `📄 *Script CSM ID ${newId}*\n📦 Tipe: ${msgType.replace(/Message$/i, '')}\n\nReply file ini + *${prefix}csm --run* untuk eksekusi.`
        }, { quoted: m })
      }
      return
    }

    // ══════════════════════════════════════════════
    // --run : Replay dari DB by ID / eksekusi .js
    // ══════════════════════════════════════════════
    if (hasRun) {
      // Jika reply ke file dokumen .js → eksekusi kodenya
      if (m.quoted && m.quoted.mtype === 'documentMessage') {
        try {
          const buf = await downloadMediaMessage(
            m.quoted.fakeObj,
            'buffer',
            {},
            { logger: alya.logger }
          )
          if (!buf) return replyalya('❌ Gagal download file .js')

          const code = buf.toString('utf8')
          // Hapus komentar header otomatis
          const cleanCode = code.replace(/^\/\*\*[\s\S]*?\*\/\s*/m, '').trim()

          const AsyncFunction = Object.getPrototypeOf(async function(){}).constructor
          const fn = new AsyncFunction(
            'alya', 'm', 'from', 'reply', 'replyalya', 'replytolak',
            'args', 'text', 'q', 'Ryuu', 'fs', 'path', 'proto',
            'getContentType', 'downloadMediaMessage',
            cleanCode
          )
          await fn(
            alya, m, m.chat, reply, replyalya, replytolak,
            args, ctx.text, ctx.q, Ryuu, fs, path, proto,
            getContentType, downloadMediaMessage
          )
        } catch (e) {
          replyalya(`❌ *CSM Run Error:*\n\`\`\`${e.message}\`\`\``)
        }
        return
      }

      // Replay dari database by ID
      if (!argId) return replyalya(`❌ Berikan ID pesan!\nContoh: *${prefix}csm --run 1*\n\nLihat list: *${prefix}csm --list*`)

      const entry = csmDb.messages[argId]
      if (!entry) return replyalya(`❌ ID *${argId}* tidak ditemukan di CSM Database.\n\nLihat list: *${prefix}csm --list*`)

      try {
        const fakeObj = proto.WebMessageInfo.fromObject({
          key: {
            remoteJid: m.chat,
            fromMe: false,
            id: require('crypto').randomBytes(8).toString('hex').toUpperCase()
          },
          message: entry.message
        })
        await alya.copyNForward(m.chat, fakeObj, true)
        await replyalya(`✅ Pesan CSM ID *${argId}* (${entry.type.replace(/Message$/i, '')}) berhasil dikirim!`)
      } catch (e) {
        replyalya(`❌ Gagal replay pesan ID ${argId}: ${e.message}`)
      }
      return
    }

    // ══════════════════════════════════════════════
    // --list : Tampilkan semua pesan di database
    // ══════════════════════════════════════════════
    if (hasList) {
      const entries = Object.values(csmDb.messages)
      if (entries.length === 0) {
        return replyalya(`📭 CSM Database masih kosong.\n\nGunakan *${prefix}csm --raw* (reply pesan) untuk menyimpan.`)
      }

      let listText = `╭─「 *CSM Database* 」\n│ Total: *${entries.length}* pesan tersimpan\n│\n`
      for (const e of entries) {
        const tgl = new Date(e.timestamp).toLocaleString('id-ID', { timeZone: 'Asia/Jakarta' })
        listText += `├ 🆔 *${e.id}* | 📦 ${e.type.replace(/Message$/i, '')}\n`
        listText += `│  👤 ${e.senderName || 'Unknown'}\n`
        listText += `│  🕒 ${tgl}\n│\n`
      }
      listText += `╰ Replay: *${prefix}csm --run [id]*`
      return replyalya(listText)
    }

    // ══════════════════════════════════════════════
    // --del : Hapus pesan dari database
    // ══════════════════════════════════════════════
    if (hasDel) {
      if (!argId) return replyalya(`❌ Berikan ID!\nContoh: *${prefix}csm --del 1*`)
      const delEntry = csmDb.messages[argId]
      if (!delEntry) return replyalya(`❌ ID *${argId}* tidak ditemukan di CSM Database.`)

      const delType = delEntry.type
      delete csmDb.messages[argId]
      saveCsmDb()
      replyalya(`🗑️ Pesan ID *${argId}* (${delType.replace(/Message$/i, '')}) berhasil dihapus dari CSM Database.`)
    }
  }
}
